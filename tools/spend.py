#!/usr/bin/env python3
"""**وحدةُ الصرف** — وحدةٌ واحدة لمقارنة الكلفة بالسقف، يستهلكها كلُّ أداةٍ تُنفق.

**العلّةُ التي وُلدت منها (مراجعة ٥٢ · R52-4 · ومقعدُ البنية F7):** السقفُ كان يُقارَن بأرقامٍ عائمة
(`spent >= args.budget`)، والعائمُ لا يمثّل السنتات تمثيلًا تامًّا: `0.1 + 0.2 == 0.3` ⇒ **False**،
وقراءتان حقيقيّتان من العدّاد (`0.3` + `2.27e-14` لكلٍّ من رصيد ٢٨٩) مجموعُهما
**`> 0.6` ⇒ True** فيُطلق التوقّفُ الاستباقيّ **سؤالًا مبكّرًا** (قِيس: ١ بدل ٢)
فقرارُ الصرف كان يتّخذ على مصادفةِ تمثيلٍ لا على رقم. والإصلاحُ
الأوّلُ كان **محلّيًّا في `eval_questions.py` وحدها** — وهي واحدةٌ من **أربعة** مواضعَ تُقارن سقفًا
(`compare_prompts` · `page_numbers` · `pos_witness` · `scale_slice`) ⇒ الصنفُ يزحف من موضعٍ لم يُغلق.

**القاعدةُ المنشورة (وتُقاس بضابط):** يُقرَّب الطرفان إلى **سنت** (تقريبٌ نصف‑صاعدٍ) ثمّ تُقارَن الأعدادُ
الصحيحة. ⇒ **التسامحُ المُعلَن ≤ ٠٫٥ سنت لكلّ طرف** (فـ`0.6049` مقابل سقف `0.60` يُقرَّب إلى `0.60`
⇒ لا تجاوز). وهو تسامحٌ أصغرُ بأربع مرّتباتٍ من هامش العائم الذي كان يُخفي رقمًا مُثبتًا هشًّا.
"""

from __future__ import annotations

import math


def cents(usd: float) -> int:
    """الدولارُ → سنتات: تقريبٌ نصف‑صاعدٍ إلى الأبعد عن الصفر، والإشارةُ محفوظة."""
    v = float(usd)
    n = int(math.floor(abs(v) * 100 + 0.5))
    return -n if v < 0 else n


def at_or_over(spent: float, cap: float) -> bool:
    """هل بلغ الصرفُ السقفَ؟ — يُسأل **بعد** الصرف (وفي بداية كلّ دورةٍ لوقفٍ حاسم)."""
    return cents(spent) >= cents(cap)


def would_exceed(spent: float, cap: float) -> bool:
    """هل يتجاوز الصرفُ السقفَ لو أُضيف؟ — يُسأل **قبل** الصرف (توقّفٌ استباقيّ)."""
    return cents(spent) > cents(cap)
