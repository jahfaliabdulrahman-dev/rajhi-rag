def is_count(x: Any) -> TypeGuard[int]:
    """**عددٌ حقيقيّ** — و`bool` صنفٌ من `int`: `True <= 133` صحيحة، فكان مانيفستٌ حقلُه `true`
    يُقرأ «ثمنًا مقيسًا» ويُطبع `PASS (True ≤ 133 صفحة محجوبة)` (قاسه مقعدا المعايير والبنية · مراجعة ٦١)."""
    return isinstance(x, int) and not isinstance(x, bool)


