"""**الأدلّةُ المحلّيّة**: `data/` لا يُنشر بالتصميم ⇒ الفحوصُ التي تقيس عليها **تُعلن تخطّيها** في نسخةٍ نقيّة.

**العطبُ الذي وُلد منه (مراجعة ٥٣، القياسُ الرابع):** نسخةٌ نقيّة من المستودع أعطت
`7 failed, 613 passed` — أربعةٌ منها تشترط وجودَ الأدلّة المحلّيّة فتفشل حيث لا وجودَ لها.
والفشلُ في نسخةٍ عامّة ليس «إنفاذًا»: يجعل رقمَ الاختبارات **بيئيّاً** (٦٥٧ عند صاحبه، وأحمرُ عند غيره)،
ويمنح المدقّقَ سبباً مشروعاً لعدم الثقة بالعدّاد. والعلاجُ الجذريّ: **الإعلانُ لا الإخفاء** —
`pytest.skip` بسببٍ مكتوب، مع بقاء التغطية كاملةً حيث توجد الأدلّة.
"""
from __future__ import annotations

import pytest

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

#: المانيفستُ هو علامةُ وجود الأدلّة المحلّيّة (`data/eval_pack/` مُهمَلٌ بالتصميم).
MANIFEST = ROOT / "data" / "eval_pack" / "amount-manifest.json"


def require_local_evidence() -> None:
    """يُعلن تخطّياً صريحاً حين لا وجودَ للأدلّة — بدل الفشل في بيئةٍ لا موضوعَ فيها للفحص."""
    if not MANIFEST.exists():
        pytest.skip("أدلّةٌ محلّيّة غيرُ موجودة (data/ لا يُنشر بالتصميم) ⇒ الفحصُ لا يُقاس في نسخةٍ نقيّة")


#: **والحاجةُ الثانيةُ — قِيس في مراجعة إغلاق ٦٤:** بيئةٌ **مستنسَخةٌ** (لا ترى جذر البيانات المشترك) تحمل
#: `data/local_sample` بلا `data/eval_pack/pack.json` كانت **تُسقط ستّةَ فحوصٍ** بـ`FileNotFoundError` —
#: أربعةٌ في `tests/test_eval_proof_rows.py` واثنان في `tests/test_eval_gate_controls.py`. أي أنّ شرطَ
#: التخطّي كان **أخشنَ من الحاجة**: يقيس وجودَ العيّنةِ وحدَها والحاجةُ عيّنةٌ **وحزمة**. والقاعدةُ هي هي:
#: **غيابُ ما يُقاس عليه إعلانٌ بالاسم، لا فشلٌ عارٍ** — فالفشلُ في نسخةٍ عامّةٍ يجعل رقمَ الاختبارات بيئيّاً.
def pack_is_present() -> bool:
    """**هل تُرى الحزمةُ المجمَّدة؟** — بالسؤال الذي تسأله الفحوصُ نفسُها: `tools/pack_io.pack_path()`.

    **ولا يُبنى المسارُ بيد — درِسٌ مدفوعة (مقعد البنية · مراجعة إغلاق ٦٤):** بنيتُ أوّلًا
    `ROOT/"data/eval_pack/pack.json"` فقِيس أنّه **يُوقف ستّةَ فحوصٍ كانت تمرّ** في شجرة المالك: الجذرُ في
    هذا المستودع يُشتقّ من `git-common-dir` (R45-2) ⇒ فحزمةُ الشجرة الأمّ تُرى من شجرةِ عملٍ فرعيّة.
    فالتخطٍّ الزائف **فقدانُ تغطيةٍ صامت** — وهو شرٌّ من الفشل الذي يُغلقه. والضابطُ يُقاس بمُحلِّل المُنتِج
    نفسِه (وهو عينُ ما تفعله ضوابطُ `tests/test_eval_gate_controls.py` كلُّها).
    """
    try:
        from tools import pack_io
        return pack_io.pack_path().exists()
    except Exception:      # لا git · لا وحدة ⇒ «غيرُ مرئيّة» (والفحصُ يُعلن تخطّيه، لا يفشل عارياً)
        return False


def require_pack() -> None:
    """تخطٍّ مُعلَن حين لا تُرى الحزمةُ المجمَّدة — بدل السقوط بـ`FileNotFoundError`."""
    if not pack_is_present():
        pytest.skip("الحزمةُ المجمَّدة غيرُ مرئيّة في هذه النسخة (data/eval_pack/ يُبنى من الكوربوس ولا يُنشر) "
                    "⇒ الفحوصُ التي تقيس عليها لا تُقاس")


def run_is_ready(run_dir: Path) -> bool:
    """**هل مجلدُ العيّنة صالحٌ للقياس؟** — بالسؤال الذي تسأله الفحوصُ نفسُها، لا بوجود المجلّد.

    **العطبُ الذي وُلد منه (مقعدُ المعايير · الدفعةُ الثالثة · مقيس):** كان الشرطُ `RUN.exists()` — وهو **أخشنُ
    من الحاجة**: مقعدٌ أنشأ `data/local_sample/slice_629p` **فارغًا** (`mkdir -p`) فمرّ الشرطُ، ثمّ
    `tools/refusal_test.py:84-86` رفع `SystemExit: لا نتائج في …` و`Corpus` لم يجد `pg-*.json` ⇒ **ثلاثةُ فحوصٍ
    سقطت فشلًا عاريًا** بدل إعلانِ تخطٍّ. والقاعدةُ هي هي التي أُغلقت مرّتين في هذه الجولة: **غيابُ ما يُقاس عليه
    إعلانٌ بالاسم لا فشلٌ عارٍ** — والمقيسُ على القرص هو `results/pg-*.json` (ما يقرؤه المُنتِج فعلًا).
    """
    return (run_dir / "results").is_dir() and bool(list((run_dir / "results").glob("pg-*.json")))


def require_run(run_dir: Path) -> None:
    """تخطٍّ مُعلَن حين لا تكون العيّنةُ جاهزةً للقياس (لا وجودٌ ولا محتوى)."""
    if not run_is_ready(run_dir):
        pytest.skip(f"العيّنةُ غيرُ جاهزةٍ في هذه النسخة (لا `results/pg-*.json` تحت {run_dir}) "
                    "⇒ الفحوصُ التي تقيس عليها لا تُقاس")

