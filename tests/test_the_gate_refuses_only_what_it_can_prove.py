"""بوّابةُ النطاق ترفض **ما تُثبته من الكشف وحدَه** — والجدولان في الاتّجاهين (قرارُ المالك 2026-11-24، الخيار ١).

**العطبُ المقيس على `ce793ff` (مسبارٌ بلا مفتاح):** ٨ من ١٤ — كلُّ الرفض الكاذب. «تحويلٌ إلى البنك الأهلي»
رُفض لأنّه «سؤالٌ عن الأهلي»، و«فندق العنوان» لأنّ فيه «العنوان»، والسنةُ ورقمُ الصفحة ويومُ التاريخ
قُرئت مبالغَ فرُفضت أسئلتُها بـ«لا مبلغ كهذا»، و«500,00» قُرئت خمسين ألفًا.

**والحدُّ المحروس:** الرفضُ الكاذبُ عطلٌ، **والتمريرُ الكاذبُ عطلٌ أيضًا** — فكلُّ جدولٍ هنا يُقاس في
اتّجاهه، ومعه حالاتٌ تتجاوزه (في الاتّجاهين) كي لا يُحفظ الجدولُ نصًّا ويُكسر ما حوله.
**ولماذا لا تكفي حزمةُ الخمسين:** لا تحوي سؤالًا واحدًا عن بنكٍ آخر (ولهذا لم تكشف العطل)، وأحكامُها
على البيانات الحقيقيّة لم يتغيّر منها شيءٌ بهذا التغيير (٤٢ يمرّ · ٨ «لا بيانات» قبله وبعده).

**الرجوع:** `git revert <sha>` لالتزام هذا الملفّ (السطرُ بقيمته في `handoff/claude/STATE.md`).
"""
from __future__ import annotations

import sys
from decimal import Decimal
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from statement_qa import scope  # noqa: E402

# حقائقُ صناعيّة لا من أيّ صفحةٍ حقيقيّة: سنةٌ واحدة · عشرون صفحة · مبلغان.
YEARS = {2024}
AMOUNTS = frozenset({Decimal("1000.00"), Decimal("500.00")})
PAGES = set(range(1, 21))


def _kind(q: str) -> str:
    return scope.classify(q, YEARS, 20, AMOUNTS, n_pages=20, pages_read=PAGES).kind


#: الجدولُ الأوّل من التكليف: **رفضٌ كاذب، يجب أن يمرّ** — بنصّه.
MUST_PASS = (
    "كم مجموع التحويلات الصادرة إلى البنك الأهلي؟",
    "هل يوجد تحويل إلى بنك الرياض؟",
    "كم دفعت للمستشفى الأهلي؟",
    "ما هي حركات فندق العنوان؟",
    "هل يوجد تحويل بمبلغ 1000 ريال في عام 2024؟",
    "هل يوجد تحويل بمبلغ 1000 ريال في الصفحة 12؟",
    "هل تم سحب يوم 15/03/2024؟",
    "هل تم دفع فاتورة 500,00 ريال؟",
)

#: الجدولُ الثاني: **رفضٌ صحيح، يجب أن يبقى** — بنصّه.
MUST_REFUSE = (
    "كم رصيدي في البنك الأهلي؟",
    "ما رصيد حسابي في بنك الرياض حول نهاية الشهر؟",
    "أعطني كشف حسابي في الأهلي للتحويل",
    "ما عنوان صاحب الحساب؟",
    "ما العنوان المسجل لصاحب الحساب؟",
    "هل يوجد سحب بمبلغ 777 ريال؟",
)

#: ما يتجاوز الجدولين — كي لا يُحفظ الجدولُ نصًّا.
ALSO_PASS = (
    "كم رصيدي بعد التحويل إلى الأهلي؟",           # المصرفُ طرفٌ والرصيدُ رصيدُ هذا الكشف
    "كم سحبت من حسابي عبر صراف بنك الرياض؟",      # المصرفُ صفةُ الصرّاف لا موضعُ الحساب
    "كم حولت للبنك الأهلي من حسابي؟",              # «لـ» حرفُ طرف
    "كم حولت إلى stc bank؟",
    "هل يوجد تحويل بمبلغ 1,000.00 ريال؟",
    "هل يوجد تحويل بمبلغ ١٠٠٠ ريال؟",
    "هل تم دفع ٥٠٠٫٠٠ ريال؟",                     # الفاصلةُ العشريّةُ العربيّة
    "هل توجد فاتورة جوال؟",
    "ما رصيد الحساب؟",
    "كم مجموع الحركات في 2024؟",
    "هل يوجد تحويل في الصفحتين 3 و4؟",
    "ما رصيد حسابي في بنك الراجحي؟",
)
ALSO_REFUSE = (
    "كم رصيد بنك الرياض؟",                         # الحسابُ مضافٌ إلى المصرف مباشرةً
    "هل عندي حساب في ساب؟",
    "رصيد حسابي في الأهلي",
    "ما رصيدي في مصرف الإنماء؟",
    "كم رصيدي في stc bank؟",
    "ما رقم جوال صاحب الحساب؟",
    "ما عنواني؟",
    "أعطني رقم الهوية",
    "كم مجموع الحركات في 2019؟",                   # سنةٌ خارج الكشف
    "ما في الصفحة 25؟",                             # صفحةٌ خارج الملفّ
    "هل يوجد تحويل بمبلغ 2000 ريال؟",               # مبلغٌ لا سنة — وغيرُ موجود
    "هل تم دفع 777,50 ريال؟",
)


@pytest.mark.parametrize("q", MUST_PASS + ALSO_PASS)
def test_what_the_gate_cannot_prove_reaches_the_tools(q: str) -> None:
    assert _kind(q) == "in_scope", q


@pytest.mark.parametrize("q", MUST_REFUSE + ALSO_REFUSE)
def test_what_the_gate_can_prove_is_refused_without_a_model(q: str) -> None:
    assert _kind(q) != "in_scope", q


def test_each_number_has_one_role() -> None:
    """السنةُ ورقمُ الصفحة ويومُ التاريخ ليست مبالغ؛ والمبلغُ ليس سنة."""
    assert scope.amounts_in("هل يوجد تحويل بمبلغ 1000 ريال في عام 2024؟") == [Decimal("1000.00")]
    assert scope.amounts_in("بمبلغ 1000 ريال في الصفحة 12") == [Decimal("1000.00")]
    assert scope.amounts_in("هل تم سحب يوم 15/03/2024؟") == []
    assert scope.amounts_in("فاتورة 500,00 ريال") == [Decimal("500.00")]
    assert scope.amounts_in("بمبلغ 1,000 ريال") == [Decimal("1000.00")]
    assert scope.amounts_in("هل يوجد سحب 777؟") == []        # بلا كلمة مال: يمرّ (مُعلَن)
    # والقارئُ الواحدُ للصفحة ما زال يرى الصفحة (لا قارئَ ثانٍ):
    assert scope.pages_in("بمبلغ 1000 ريال في الصفحة 12") == [12]


def test_the_refusal_is_the_same_on_every_run() -> None:
    """الحتميّةُ هي سببُ وجود البوّابة: السؤالُ نفسُه ⇒ الجوابُ نفسُه."""
    q = "كم رصيدي في البنك الأهلي؟"
    a = scope.classify(q, YEARS, 20, AMOUNTS)
    assert a.kind == "out_of_scope" and scope.REFUSAL in a.answer
    assert scope.classify(q, YEARS, 20, AMOUNTS).answer == a.answer
